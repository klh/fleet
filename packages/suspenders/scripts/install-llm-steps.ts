const kitDir = (ctx: StepContext): string => join(ctx.repo, "..", "local-llm");
const beltBin = (ctx: StepContext): string =>
	join(ctx.repo, "..", "belt", "bin");

const logFor = (ctx: StepContext): ((line: string) => void) => {
	const sink = ctx.json ? console.error : console.log;
	return (line: string): void => {
		sink(line);
	};
};

export interface LiteLlmMetricsDeps {
	python?: string;
	uv?: string | null;
	probe?: (python: string) => string | null;
	run?: (args: string[]) => Promise<number>;
}

/** Repair the exact uv tool environment before enabling native metrics.
 * The proxy itself never installs dependencies; this runs during install. */
export async function ensureLiteLlmMetricsDependency(
	deps: LiteLlmMetricsDeps = {},
): Promise<"present" | "installed"> {
	const python = deps.python ?? DEFAULT_PATHS.python;
	const probe =
		deps.probe ??
		((path: string) => prismaPreflight(path) ?? prometheusPreflight(path));
	if (probe(python) === null) return "present";
	const uv = deps.uv === undefined ? Bun.which("uv") : deps.uv;
	if (!uv)
		throw new Error("uv missing; LiteLLM metrics dependency unavailable");
	const args = litellmToolInstallArgs(uv);
	const run =
		deps.run ??
		(async (argv: string[]): Promise<number> => {
			const child = Bun.spawn(argv, {
				stdin: "ignore",
				stdout: "ignore",
				stderr: "ignore",
				timeout: 300_000,
			});
			return await child.exited;
		});
	const code = await run(args);
	if (code !== 0)
		throw new Error(`LiteLLM metrics tool install exited ${code}`);
	const missing = probe(python);
	if (missing !== null)
		throw new Error(`LiteLLM metrics preflight: ${missing}`);
	return "installed";
}

// ─── gateway-config regen (W889) ───

/** Generator files that ride NO import closure — the closure heal never
 *  refreshes them; the regen leg syncs them kit→home itself. */
const GENERATOR_FILES = [
	"gateway-config.ts",
	"remotes-validate.ts",
	"openrouter-free-rows.ts",
	"zai-catalog-rows.ts",
	"chatgpt-subscription-rows.ts",
];

/** Home files whose bytes the GENERATED yaml depends on: the generator
 *  code plus the operator-owned routing policy. */
const GENERATOR_INPUTS = [
	...GENERATOR_FILES,
	"router-policy.ts",
	"routing-policy.yaml",
];

const GENERATED_STAMP = /^# GENERATED by belt gateway tooling \(([^)]+)\)/m;

/** W889 staleness guard: litellm.yaml missing, stampless, or its GENERATED
 *  timestamp older than any generator input mtime (code or operator
 *  policy). A stampless hand edit counts as stale. */
export const gatewayConfigStale = (home: string): boolean => {
	const yaml = join(home, "litellm.yaml");
	if (!existsSync(yaml)) return true;
	const m = readFileSync(yaml, "utf8").match(GENERATED_STAMP);
	const stamp = m ? Date.parse(m[1]) : Number.NaN;
	if (!Number.isFinite(stamp)) return true;
	return GENERATOR_INPUTS.some((name) => {
		const p = join(home, name);
		return existsSync(p) && statSync(p).mtimeMs > stamp;
	});
};

export interface RegenDeps {
	/** generator runner override (tests); default spawns the home copy with
	 *  HOME pinned to the home's `.claude` parent */
	run?: (argv: string[], homeRoot: string) => Promise<void>;
}

const defaultRun = async (argv: string[], homeRoot: string): Promise<void> => {
	const child = Bun.spawn(argv, {
		env: { ...process.env, HOME: homeRoot },
		stdin: "ignore",
		stdout: "pipe",
		stderr: "pipe",
		timeout: 120_000,
	});
	const [code, err] = await Promise.all([
		child.exited,
		new Response(child.stderr).text(),
	]);
	if (code !== 0) {
		const tail = err.trim().split("\n").filter(Boolean).slice(-1)[0];
		throw new Error(`rc=${code}${tail ? ` ${tail}` : ""}`);
	}
};

/** W889: post-copy generator sync + staleness-guarded regeneration. Syncs
 *  the no-closure generator files kit→home, then re-runs the home
 *  generator when the yaml's GENERATED stamp trails an input mtime. Only
 *  fires on the canonical flat home (`<root>/.claude/local-llm`) — the
 *  generator derives its own paths from HOME. Failure degrades to a note:
 *  the last good yaml stays, activation stays the kill-:4100 operator
 *  action. */
export async function regenGatewayConfig(
	ctx: StepContext,
	deps: RegenDeps = {},
): Promise<string | null> {
	const parent = dirname(ctx.llmHome);
	if (basename(parent) !== ".claude") return null; // non-canonical home
	const kitBin = beltBin(ctx);
	for (const name of GENERATOR_FILES) {
		const from = join(kitBin, name);
		if (!existsSync(from)) continue;
		const to = join(ctx.llmHome, name);
		if (existsSync(to) && readFileSync(from).equals(readFileSync(to))) continue;
		copyFileSync(from, to);
	}
	const generator = join(ctx.llmHome, "gateway-config.ts");
	if (!existsSync(generator)) return null;
	if (!gatewayConfigStale(ctx.llmHome)) return null;
	try {
		await (deps.run ?? defaultRun)(
			[process.execPath, generator],
			dirname(parent),
		);
	} catch (err) {
		return `gateway config regen FAILED (${err instanceof Error ? err.message : String(err)}) — last good litellm.yaml stays`;
	}
	return `gateway config regenerated from the healed kit (${join(ctx.llmHome, "litellm.yaml")}; activate: kill :4100 between fan-outs)`;
}

// ─── seedLocalLlm ───

export async function seedLocalLlm(ctx: StepContext): Promise<StepResult> {
	if (ctx.noLlm === true) {
		return {
			status: "skipped",
			note: "--no-llm: local-llm baseline skipped (CI/containers)",
		};
	}
	const swarmEntry = join(beltBin(ctx), "swarm.ts");
	if (!existsSync(swarmEntry)) {
		return {
			status: "skipped",
			note: "not a fleet checkout — no belt/bin kit sibling to seed from",
		};
	}
	const log = logFor(ctx);
	mkdirSync(ctx.llmHome, { recursive: true });
	const beltEnv = join(ctx.llmHome, "belt.env");
	if (!existsSync(beltEnv)) {
		copyFileSync(join(kitDir(ctx), "belt.env"), beltEnv);
		chmodSync(beltEnv, 0o600);
		log(`+ ${beltEnv} (stub — configure before install)`);
	}
	const guard = validateBeltWiredGuard(beltEnv);
	if (!guard.ok)
		return {
			status: "failed",
			note: `${guard.reason}; configure ${beltEnv} before install`,
		};
	if (ctx.llmHome === join(process.env.HOME ?? "", ".claude", "local-llm")) {
		try {
			const state = await ensureLiteLlmMetricsDependency();
			log(`LiteLLM Prometheus dependency ${state}`);
		} catch (err) {
			return {
				status: "failed",
				note: `LiteLLM native metrics dependency failed — ${err instanceof Error ? err.message : String(err)}`,
			};
		}
	}
	// W778: the flattened kit now imports npm deps (stack-config.ts → yaml)
	// and the home has no manifest of its own — ride the prefix's offline
	// node_modules (idempotent; a real operator dir is left alone).
	const nm = join(ctx.llmHome, "node_modules");
	const wantNm = join(ctx.prefix, "node_modules");
	if (existsSync(wantNm) && !existsSync(nm)) {
		symlinkSync(wantNm, nm);
		log(`~ ${nm} → ${wantNm} (flat-home npm resolution)`);
	}
	// W284: heal the belt closure for BOTH entries — the supervisor
	// (swarm.ts supervise) and the :4000 router — so the home copy of
	// swarm.ts always matches the belt kit; the W556 keep-rule retired
	// with the serve fork. W661: prove the flattened runtime actually
	// serves on a scratch port.
	try {
		const sup = await refreshFlatHome(
			ctx.llmHome,
			join(beltBin(ctx), "swarm.ts"),
			undefined,
			log,
		);
		const report = await refreshFlatHome(
			ctx.llmHome,
			join(beltBin(ctx), "router-shim.ts"),
			undefined,
			log,
		);
		await smokeRouter(ctx.llmHome);
		log(
			`belt closure: supervisor ${sup.healed.length} healed, ${sup.kept.length} kept; router ${report.healed.length} healed, ${report.kept.length} kept; router smoke ok`,
		);
	} catch (err) {
		return {
			status: "failed",
			note: `belt closure refresh or router smoke failed — ${err instanceof Error ? err.message : String(err)}`,
		};
	}
	// W507: the tier choice is machine config — every install re-emits the
	// manifest the swarm supervisor and llm-keepwarm read. Absent emitter or
	// a stale kit copy degrades to a note, never a failed install.
	const emitter = join(ctx.llmHome, "registry-emit.ts");
	if (existsSync(emitter)) {
		const tier = join(ctx.llmHome, "tier.json");
		const child = Bun.spawn(
			[process.execPath, emitter, "tier", "--out", tier],
			{
				env: { ...process.env, BELT_TIER: "minimal" },
				stdout: "ignore",
				stderr: "pipe",
			},
		);
		const code = await child.exited;
		if (code !== 0) {
			log("tier manifest emission skipped (stale kit registry-emit.ts)");
		}
	}
	// W284: routing-policy default rides the belt kit. The private belt.env
	// was validated before any supervisor closure was installed.
	const stubs: Array<[string, string]> = [
		["routing-policy.yaml", join(beltBin(ctx), "routing-policy.yaml")],
	];
	for (const [stub, source] of stubs) {
		const target = join(ctx.llmHome, stub);
		if (existsSync(target)) {
			log(`= ${target} kept (operator-owned runtime copy)`);
		} else {
			copyFileSync(source, target);
			log(`+ ${target} (stub — fill/verify at activation)`);
		}
	}
	// W889: the heal never re-ran the gateway generator — W219.2's fallback
	// fix sat present-not-live in litellm.yaml for days (yaml generated
	// 10-15, heal 10-19 15:30). Post-copy: sync the no-closure generator
	// files, staleness-guard the yaml, regenerate when inputs moved.
	const regen = await regenGatewayConfig(ctx);
	if (regen) log(regen);
	return {
		status: "ok",
		note: `belt kit seeded at ${ctx.llmHome} (supervise closure healed; router smoke ok)${regen ? `; ${regen}` : ""}`,
	};
}

// ─── downloadModels ───

export interface DownloadDeps {
	/** force the mlx-lm python path; null = treated as missing; undefined = discover */
	pythonPath?: string | null;
	/** force the model list; undefined = derive from the registry */
	models?: string[];
	/** per-model download runner; overridable for tests */
	spawnDownload?: (python: string, model: string) => Promise<number>;
}

const DOWNLOAD_SNIPPET =
	"from huggingface_hub import snapshot_download; import sys; snapshot_download(sys.argv[1])";

const mlxPython = (): string =>
	join(process.env.HOME ?? "", ".local/share/uv/tools/mlx-lm/bin/python");

async function defaultDownloadRunner(
	python: string,
	model: string,
): Promise<number> {
	const child = Bun.spawn([python, "-c", DOWNLOAD_SNIPPET, model], {
		stdin: "ignore",
		stdout: "ignore",
		stderr: "inherit",
	});
	return await child.exited;
}

/** BELT_TIER=minimal resident set from the home registry, belt kit fallback. */
async function residentModels(ctx: StepContext): Promise<string[]> {
	const home = join(ctx.llmHome, "registry.ts");
	const source = existsSync(home) ? home : join(beltBin(ctx), "registry.ts");
	const prior = process.env.BELT_TIER;
	process.env.BELT_TIER = "minimal";
	try {
		const mod = (await import(source)) as {
			residentSet: () => Array<{ model: string }>;
		};
		return mod.residentSet().map((s) => s.model);
	} finally {
		if (prior === undefined) delete process.env.BELT_TIER;
		else process.env.BELT_TIER = prior;
	}
}

export async function downloadModels(
	ctx: StepContext,
	deps: DownloadDeps = {},
): Promise<StepResult> {
	if (ctx.noLlm === true) {
		return {
			status: "skipped",
			note: "--no-llm: model download skipped (CI/containers)",
		};
	}
	if (ctx.skipModels === true) {
		return {
			status: "skipped",
			note: "--skip-models: skipping model download (offline install)",
		};
	}
	if (!existsSync(join(beltBin(ctx), "swarm.ts"))) {
		return {
			status: "skipped",
			note: "not a fleet checkout — no belt/bin kit sibling to derive models from",
		};
	}
	const log = logFor(ctx);
	let python = deps.pythonPath !== undefined ? deps.pythonPath : mlxPython();
	if (python === null && deps.pythonPath === undefined) {
		// legacy parity: one best-effort uv install before giving up
		const uv = Bun.which("uv");
		if (uv !== null) {
			const child = Bun.spawn([uv, "tool", "install", "mlx-lm"], {
				stdin: "ignore",
				stdout: "ignore",
				stderr: "ignore",
			});
			await child.exited;
		}
		python = existsSync(mlxPython()) ? mlxPython() : null;
	}
	if (python === null) {
		return {
			status: "skipped",
			note: "mlx-lm missing — skipping model download (re-run install to fetch)",
		};
	}
	const models = deps.models ?? (await residentModels(ctx));
	if (models.length === 0) {
		return {
			status: "ok",
			note: "no BELT_TIER=minimal resident models to download",
		};
	}
	const run = deps.spawnDownload ?? defaultDownloadRunner;
	const failedModels: string[] = [];
	for (const model of models) {
		log(`→ downloading ${model} (resumes if partial)`);
		const code = await run(python, model);
		if (code !== 0) {
			failedModels.push(model);
			log(`  ✗ ${model} failed — re-run install to resume`);
		}
	}
	if (failedModels.length > 0) {
		return {
			status: "ok",
			note: `${failedModels.length} of ${models.length} model downloads failed (resumable)`,
			detail: failedModels.join(", "),
		};
	}
	return {
		status: "ok",
		note: `downloaded ${models.length} resident model(s) via mlx-lm`,
	};
}

// ─── refreshSupervisor ───

export interface SupervisorDeps {
	/** import validation override (tests); default spawns `bun -e await import` */
	validate?: (file: string) => Promise<void>;
	/** belt supervisor source override (tests); default belt/bin/supervisor.ts */
	supervisorSource?: string;
	/** belt health source override (tests); default belt/bin/health.ts */
	healthSource?: string;
}

async function defaultValidate(file: string): Promise<void> {
	const child = Bun.spawn(
		[process.execPath, "-e", "await import(process.argv[1])", file],
		{ stdout: "ignore", stderr: "ignore" },
	);
	const timer = setTimeout(() => child.kill(), 30_000);
	try {
		if ((await child.exited) !== 0) {
			throw new Error("supervisor import validation failed");
		}
	} finally {
		clearTimeout(timer);
	}
}

export async function refreshSupervisor(
	ctx: StepContext,
	deps: SupervisorDeps = {},
): Promise<StepResult> {
	const swarm = join(ctx.llmHome, "swarm.ts");
	if (!existsSync(swarm)) {
		return {
			status: "failed",
			note: "--refresh-supervisor requires an existing belt supervisor runtime",
		};
	}
	// W284: the belt family is the only family (the kit-serve branch and
	// refresh-swarm.ts retired with the serve fork). Backup, refresh,
	// import-validate, restore on failure.
	const swarmSource = readFileSync(swarm, "utf8");
	if (!swarmSource.includes('from "./supervisor.ts"')) {
		return {
			status: "failed",
			note: "not a belt supervisor runtime (swarm.ts lacks the supervisor import) — run seedLocalLlm first",
		};
	}
	const source = deps.supervisorSource ?? join(beltBin(ctx), "supervisor.ts");
	const target = join(ctx.llmHome, "supervisor.ts");
	if (!existsSync(target)) {
		return {
			status: "failed",
			note: "--refresh-supervisor requires an existing belt supervisor runtime",
		};
	}
	const backup = `${target}.before-refresh`;
	copyFileSync(target, backup);
	try {
		copyFileSync(source, target);
		copyFileSync(
			deps.healthSource ?? join(beltBin(ctx), "health.ts"),
			join(ctx.llmHome, "health.ts"),
		);
		await (deps.validate ?? defaultValidate)(target);
	} catch (err) {
		copyFileSync(backup, target);
		return {
			status: "failed",
			note: `supervisor import failed; previous code restored — ${err instanceof Error ? err.message : String(err)}`,
		};
	}
	return {
		status: "ok",
		note: "refreshed supervisor code (restart com.suspenders.belt-swarm to activate)",
	};
}
