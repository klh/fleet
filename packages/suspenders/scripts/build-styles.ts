// scripts/build-styles.ts — the ONE style build face (W2267.8 decisions +
// W2267.4.2.2 components): compiles the same-name .scss sources through
// @klh/design-ui's compileStylesheet into generated CSS modules — string
// modules the board page interpolates (decisions) and Lit CSSResult
// static styles the components adopt (task-card, card-activity). Sass
// computes structure at build time; the theme rides the kernel layer's
// --klh-* custom properties at runtime, so every generated sheet is
// theme-free (semantic tokens only). package.json's build:styles runs
// this file verbatim; editing a generated file is always wrong — edit
// the .scss.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { compileStylesheet } from "@klh/design-ui/build/scss-plugin.ts";

const ROOT = resolve(import.meta.dir, "..");

/** Same-name pairs: hooks/board-html/<name>.scss → <name>-css.ts exporting
 *  <ENTITY>_STYLES (a Lit CSSResult). */
const PAIRS = [
	{
		scss: "hooks/board-html/klh-task-card.scss",
		out: "hooks/board-html/klh-task-card-css.ts",
		entity: "TASK_CARD_STYLES",
	},
	{
		scss: "hooks/board-html/klh-card-activity.scss",
		out: "hooks/board-html/klh-card-activity-css.ts",
		entity: "CARD_ACTIVITY_STYLES",
	},
] as const;

/** Compile every same-name .scss → its generated Lit style module. */
export function buildComponentStyles(): string[] {
	return PAIRS.map((p) => {
		const css = compileStylesheet(join(ROOT, p.scss));
		const mod = [
			`// GENERATED by scripts/build-styles.ts — edit ${p.scss.split("/").pop()}, never this file.\n`,
			'import { css, unsafeCSS } from "lit";\n',
			`export const ${p.entity} = css\`\${unsafeCSS(`,
			JSON.stringify(css),
			")}`;\n",
		].join("");
		writeFileSync(join(ROOT, p.out), mod);
		return p.out;
	});
}

const DECISIONS_SCSS = join(ROOT, "hooks/board-html/decisions.scss");
const DECISIONS_OUT = join(ROOT, "hooks/board-html/decisions-css.ts");

/** Compile decisions.scss → the DECISIONS_CSS string module. */
export function buildDecisionsStyles(): string {
	const css = compileStylesheet(DECISIONS_SCSS);
	const mod = [
		"// GENERATED by scripts/build-styles.ts — edit decisions.scss, never this file.\n",
		"export const DECISIONS_CSS = ",
		JSON.stringify(css),
		";\n",
	].join("");
	writeFileSync(DECISIONS_OUT, mod);
	return css;
}

if (import.meta.main) {
	const outs = buildComponentStyles();
	for (const o of outs) console.log(`component styles → ${o}`);
	const css = buildDecisionsStyles();
	console.log(`decisions styles → ${DECISIONS_OUT} (${css.length} bytes css)`);
}
