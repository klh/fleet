// scss-plugin.ts — W2269.1.1: SCSS → Lit static styles. Sass computes at
// build time; CSS custom properties carry the theme at runtime, so the
// compiled sheet passes through shadow DOM and changes with data-theme.
// One stylesheet per component: <name>.scss next to <name>.ts, compiled
// here into a module the component imports as `static styles`.
import { writeFileSync } from "node:fs";
import sass from "sass";

/** Compile a component stylesheet to plain CSS text. */
export const compileStylesheet = (scssPath: string): string =>
	sass.compile(scssPath).css;

/** Emit a Lit static-styles module from a component .scss file. */
export const emitStylesModule = (scssPath: string, outPath: string): void => {
	const css = compileStylesheet(scssPath);
	const mod = [
		"// GENERATED by src/build/scss-plugin.ts — edit the .scss source, never this file.\n",
		'import { css, unsafeCSS } from "lit";\n',
		`export const styles = css\`\${unsafeCSS(${JSON.stringify(css)})}\`;\n`,
	].join("");
	writeFileSync(outPath, mod);
};
